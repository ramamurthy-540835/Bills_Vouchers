import {test,expect} from '../../frontend/node_modules/@playwright/test'
test.beforeEach(async({context,request,baseURL})=>{
 test.skip(Boolean(process.env.BV_TEST_URL),'Local synthetic businesses only')
 await request.post('http://127.0.0.1:8103/__test__/reset')
 await context.addCookies([{name:'session',value:'local-browser-test',url:baseURL!}])
})
test('Business profile layout, membership switching and refresh',async({page})=>{
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('/settings/profile')
 await expect(page.getByRole('heading',{name:'My Businesses',exact:true})).toBeVisible()
 await expect(page.locator('.business-list-card')).toHaveCount(3)
 await expect(page.getByRole('link',{name:'+ Add Business',exact:true})).toBeVisible()
 await expect(page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Business Profile'})).toHaveCount(0)
 const actions=page.locator('.business-profile-page .button')
 for(const action of await actions.all()){
  await expect(action).toHaveCSS('background-color','rgb(24, 118, 83)')
  await expect(action).toHaveCSS('color','rgb(255, 255, 255)')
 }
 const add=page.getByRole('link',{name:'+ Add Business',exact:true})
 await add.hover();await expect(add).toHaveCSS('background-color','rgb(18, 92, 64)')
 await add.focus();await expect(add).toHaveCSS('outline-style','solid')
 await page.mouse.move(0,0)
 const geometry=async()=>page.locator('.business-list-card').evaluateAll(cards=>cards.map(card=>{const rect=card.getBoundingClientRect(),button=card.querySelector('.business-card-actions .button')!.getBoundingClientRect();return {top:rect.top,height:rect.height,bottom:button.bottom,width:button.width}}))
 const desktop=await geometry()
 expect(new Set(desktop.map(card=>card.top)).size).toBe(1)
 expect(new Set(desktop.map(card=>card.height)).size).toBe(1)
 expect(new Set(desktop.map(card=>card.bottom)).size).toBe(1)
 expect(Math.max(...desktop.map(card=>card.width))-Math.min(...desktop.map(card=>card.width))).toBeLessThan(1)
 await page.screenshot({path:'../artifacts/gst_easy/business-profile-desktop.png',fullPage:true})
 await page.setViewportSize({width:1100,height:900})
 const tablet=await geometry()
 expect(tablet[0].top).toBe(tablet[1].top)
 expect(tablet[2].top).toBeGreaterThan(tablet[0].top)
 await page.screenshot({path:'../artifacts/gst_easy/business-profile-tablet.png',fullPage:true})

 await page.setViewportSize({width:390,height:844})
 const mobile=await geometry()
 expect(new Set(mobile.map(card=>card.top)).size).toBe(3)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await page.screenshot({path:'../artifacts/gst_easy/business-profile-mobile.png',fullPage:true})
 await page.getByRole('button',{name:'Switch to Business Synthetic Read Only',exact:true}).click()
 await expect(page.getByLabel('Legal name',{exact:true})).toHaveValue('Synthetic Read Only')
 await expect(page.getByRole('button',{name:'Save business details'})).toHaveCount(0)
 await page.reload()
 await expect(page.getByLabel('Legal name',{exact:true})).toHaveValue('Synthetic Read Only')
 await expect(page.locator('.business-list-card').filter({hasText:'Active business'})).toContainText('Synthetic Read Only')
})
