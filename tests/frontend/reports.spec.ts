test('report back button placement, hover, keyboard focus and retained context',async({page})=>{
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('/reports/cash-requirement?period=2026-09&range=quarter')
 const back=page.getByRole('link',{name:/Back to Reports/})
 await expect(back).toHaveAttribute('href','/reports?period=2026-09&range=quarter')
 const header=await page.locator('.report-detail-header').boundingBox()
 const button=await back.boundingBox()
 expect(Math.abs(button!.x+button!.width-header!.x-header!.width)).toBeLessThan(2)
 expect(Math.abs(button!.y-header!.y)).toBeLessThan(2)
 await back.hover()
 await expect(back).toHaveCSS('background-color','rgb(18, 92, 64)')
 await page.mouse.move(0,0)
 await back.focus()
 await page.keyboard.press('Shift+Tab')
 await page.keyboard.press('Tab')
 await expect(back).toBeFocused()
 expect(await back.evaluate(el=>el.matches(':focus-visible'))).toBeTruthy()
 await expect(back).toHaveCSS('outline-style','solid')
 await page.screenshot({path:'../artifacts/gst_easy/report-back-desktop.png',fullPage:true})
 await page.getByLabel('Account menu',{exact:true}).click()
 await page.getByLabel('Switch business',{exact:true}).selectOption('browser-readonly')
 await expect(page.getByRole('region',{name:'Business reports'})).toContainText('browser-readonly')
 await page.setViewportSize({width:390,height:844})
 const mobileButton=await back.boundingBox()
 const title=await page.locator('.report-detail-header h2').boundingBox()
 expect(mobileButton!.y).toBeGreaterThanOrEqual(title!.y+title!.height)
 expect(mobileButton!.x+mobileButton!.width).toBeLessThanOrEqual(390)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await page.screenshot({path:'../artifacts/gst_easy/report-back-mobile.png',fullPage:true})
 const destination=new URL((await back.getAttribute('href'))!,'http://localhost:3100')
 await back.click()
 await expect(page).toHaveURL(url=>url.pathname==='/reports'&&url.searchParams.get('period')===destination.searchParams.get('period')&&url.searchParams.get('range')===destination.searchParams.get('range'))
 await expect(page.getByRole('region',{name:'Business reports'})).toContainText('browser-readonly')
})
